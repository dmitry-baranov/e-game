CREATE TABLE experiment_series (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_json text NOT NULL,
    created_at timestamp without time zone,
    generator_version varchar(255),
    mode varchar(255),
    model_version varchar(255),
    next_number integer NOT NULL,
    policy_version varchar(255),
    status varchar(255),
    target integer NOT NULL DEFAULT 0,
    CONSTRAINT ck_experiment_series_mode CHECK (mode IS NULL OR mode IN ('COLLECT', 'EVALUATE')),
    CONSTRAINT ck_experiment_series_status CHECK
        (status IS NULL OR status IN ('RUNNING', 'PAUSED', 'DONE', 'EXHAUSTED', 'STOPPED')),
    CONSTRAINT ck_experiment_series_target CHECK (target >= 0),
    CONSTRAINT ck_experiment_series_next_number CHECK (next_number > 0)
);

CREATE TABLE experiment_pair (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_id bigint NOT NULL REFERENCES experiment_series(id) ON DELETE CASCADE,
    pair_number integer NOT NULL,
    seed bigint NOT NULL,
    market varchar(255) NOT NULL,
    status varchar(32) NOT NULL DEFAULT 'PENDING',
    CONSTRAINT uk_experiment_pair_series_number UNIQUE (series_id, pair_number),
    CONSTRAINT ck_experiment_pair_number CHECK (pair_number > 0),
    CONSTRAINT ck_experiment_pair_status CHECK
        (status IN ('PENDING', 'RUNNING', 'WAITING', 'COMPLETED', 'INCOMPLETE', 'ERROR', 'CANCELLED'))
);

