-- Empty-database baseline for the game, experiments, ML reporting and Spring infrastructure.

CREATE TABLE account (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(255),
    full_name varchar(255),
    password varchar(255),
    role varchar(255),
    service_account boolean NOT NULL DEFAULT false,
    service_account_type varchar(64),
    CONSTRAINT ck_account_role CHECK (role IS NULL OR role IN ('USER', 'ADMIN')),
    CONSTRAINT ck_account_service_type CHECK
        ((service_account AND service_account_type IS NOT NULL) OR
         (NOT service_account AND service_account_type IS NULL)),
    CONSTRAINT uk_account_email UNIQUE (email)
);

CREATE TABLE game (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    absolute_quality_product_life integer,
    advertisement_weight numeric(38,2),
    assortment_weight numeric(38,2),
    base_advertisement_price numeric(38,2),
    base_cost_price numeric(38,2),
    current_day integer,
    daily_spending_limit numeric(38,2),
    end_date timestamp without time zone,
    habit_tracking_days integer,
    habit_weight numeric(38,2),
    interest_rate_business_credit numeric(38,2),
    interest_rate_investment_credit numeric(38,2),
    investment_credit_term_months numeric(38,2),
    name varchar(255),
    product_power numeric(38,2),
    purchase_limit integer,
    quality_weight numeric(38,2),
    sales_tax numeric(38,2),
    start_date timestamp without time zone,
    status varchar(255),
    time_unit integer
);

