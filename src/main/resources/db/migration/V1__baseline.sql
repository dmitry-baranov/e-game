    entered_initial_production_parameters boolean NOT NULL,
    investment_credit_amount numeric(38,2),
    investment_credit_debt numeric(38,2),
    investment_credit_is_repaid boolean,
    investment_credit_term_months numeric(38,2),
    production_capacity_per_day integer,
